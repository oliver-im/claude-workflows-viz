import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { Resvg } from "@resvg/resvg-js";

/**
 * Regenerate `ts/text-metrics-data.ts`: per-character advance widths, in 1/1000
 * em, for the faces the renderer's font stacks resolve to — Helvetica (Arial and
 * Liberation Sans share its widths, which is why the sans stack lists exactly
 * those three) and Menlo for the mono stack.
 *
 * Widths are measured with resvg itself, so the table matches what the PNG
 * rasterizer draws: each advance is (bbox of "|c|c|…|c|") − (bbox of the same bars
 * alone), over 20 repeats. Interleaving with a bar keeps same-glyph kerning pairs
 * (Helvetica kerns "11") out of the measurement, and the bars' side bearings cancel
 * exactly. Run on macOS, where those faces are system fonts. This is a dev-time
 * generator, not part of the renderer; the committed table is the input, so
 * renders stay deterministic.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "ts", "text-metrics-data.ts");

const REPEAT = 20;
const SIZE = 1000;

/** Common non-ASCII glyphs worth an exact width; anything else falls back. */
const EXTRAS = "—–…·×→←’‘“”•°±≤≥≠÷€£¥©®™§¶";

function bboxWidth(family, weight, style, content) {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="40000" height="2000">` +
    `<text x="100" y="1500" xml:space="preserve" font-family="${family}" font-size="${SIZE}" ` +
    `font-weight="${weight}" font-style="${style}">${content}</text></svg>`;
  const bb = new Resvg(svg, { font: { loadSystemFonts: true } }).getBBox();
  if (!bb) throw new Error(`no bbox for ${JSON.stringify(content)} in ${family}`);
  return bb.width;
}

function escapeXml(c) {
  return c === "&" ? "&amp;" : c === "<" ? "&lt;" : c === ">" ? "&gt;" : c;
}

function measureFace(family, weight, style) {
  const bars = bboxWidth(family, weight, style, "|".repeat(REPEAT + 1));
  const widths = {};
  const chars = [];
  for (let code = 32; code <= 126; code++) chars.push(String.fromCharCode(code));
  for (const c of EXTRAS) chars.push(c);
  for (const c of chars) {
    const w = bboxWidth(family, weight, style, `|${`${escapeXml(c)}|`.repeat(REPEAT)}`);
    widths[c] = Math.round(((w - bars) / REPEAT / SIZE) * 1000 * 10) / 10;
  }
  return widths;
}

const faces = {
  sans: measureFace("Helvetica", 400, "normal"),
  sansBold: measureFace("Helvetica", 700, "normal"),
  sansItalic: measureFace("Helvetica", 400, "italic"),
};
const menlo = measureFace("Menlo", 400, "normal");
const monoAdvance = menlo.M;
for (const [c, w] of Object.entries(menlo)) {
  if (Math.abs(w - monoAdvance) > 1 && c.charCodeAt(0) < 127) {
    throw new Error(`Menlo is not monospaced at ${JSON.stringify(c)}: ${w} vs ${monoAdvance}`);
  }
}

const table = (name, widths) =>
  `export const ${name}: Readonly<Record<string, number>> = {\n` +
  Object.entries(widths)
    .map(([c, w]) => `  ${JSON.stringify(c)}: ${w},`)
    .join("\n") +
  `\n};\n`;

writeFileSync(
  out,
  [
    "// GENERATED by scripts/gen-text-metrics.mjs — do not edit by hand.",
    "// Advance widths in 1/1000 em, measured with resvg on macOS.",
    "",
    table("SANS_REGULAR", faces.sans),
    table("SANS_BOLD", faces.sansBold),
    table("SANS_ITALIC", faces.sansItalic),
    `/** Menlo's single advance; every ASCII glyph in the mono stack shares it. */`,
    `export const MONO_ADVANCE = ${monoAdvance};`,
    "",
  ].join("\n"),
);
console.log(`Wrote ${out} (mono advance ${monoAdvance})`);
