import { type Capture, PROSE_FILE, SCHEMA_FILE, type Segment } from "./capture.js";
import type { CaptureDiff, Excerpt } from "./diff.js";

/**
 * Markdown for the readable side of `spec/`: a capture's prose as a page, the
 * change page between two captures, and the captures table the reference embeds.
 *
 * The prose is already written in Markdown's idiom (`**bold**`, backticked code,
 * `- ` lists, `#` headings), so the page keeps every word and only fixes what
 * stops it rendering: escapes are decoded (in `capture.ts`), the indented
 * examples become fenced code blocks, line breaks are kept as hard breaks, and
 * the few characters GitHub would misread (`<any>` as a tag, `~10` as
 * strikethrough) are escaped.
 */

export const GENERATED_NOTE = "<!-- Generated by `npm run spec` (ts/spec/). Do not edit this file; edit the generator. -->";

// ---------------------------------------------------------------------------
// A capture's prose → blocks
// ---------------------------------------------------------------------------

type Block =
  | { kind: "heading"; depth: number; items: Segment[] }
  | { kind: "paragraph"; lines: Segment[][] }
  | { kind: "list"; items: Array<{ items: Segment[]; code: string[] | null }> }
  | { kind: "code"; lines: string[] };

type LineKind = "blank" | "code" | "heading" | "item" | "prose";

/** Split segments at newlines; values and conditionals stay on the line they sit in. */
function splitLines(segments: readonly Segment[]): Segment[][] {
  const lines: Segment[][] = [[]];
  for (const s of segments) {
    if (s.kind !== "text") {
      lines[lines.length - 1].push(s);
      continue;
    }
    s.text.split("\n").forEach((part, i) => {
      if (i > 0) lines.push([]);
      if (part) lines[lines.length - 1].push({ kind: "text", text: part });
    });
  }
  return lines;
}

function lineKind(line: Segment[]): LineKind {
  const head = line[0];
  if (line.every((s) => s.kind === "text" && !/\S/.test(s.text))) return "blank";
  if (head?.kind !== "text") return "prose";
  if (/^\s/.test(head.text)) return "code";
  if (/^#{1,6} /.test(head.text)) return "heading";
  if (head.text.startsWith("- ")) return "item";
  return "prose";
}

/** A code line as written: values and conditionals stay in their source spelling. */
function codeText(line: Segment[]): string {
  return line
    .map((s) => {
      switch (s.kind) {
        case "text":
          return s.text;
        case "value":
          return `\${${s.name}}`;
        case "conditional":
          return `${marker(s)}${s.text}«/if»`;
        case "expression":
          return `\${${s.source}}`;
      }
    })
    .join("");
}

/** Drop a fixed prefix (a heading's `#`s, a list bullet) off a line's first text segment. */
function dropPrefix(line: Segment[], prefix: RegExp): Segment[] {
  const [head, ...rest] = line;
  if (head?.kind !== "text") return line;
  const text = head.text.replace(prefix, "");
  return text ? [{ kind: "text", text }, ...rest] : rest;
}

function dedent(lines: string[]): string[] {
  const indents = lines.filter((l) => /\S/.test(l)).map((l) => /^ */.exec(l)![0].length);
  const cut = indents.length > 0 ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(cut).trimEnd());
}

function parseBlocks(segments: readonly Segment[]): Block[] {
  const lines = splitLines(segments);
  const blocks: Block[] = [];
  const takeCode = (i: number): [string[], number] => {
    const code: string[] = [];
    // A blank line stays inside an example only when the example continues past it.
    while (i < lines.length) {
      const kind = lineKind(lines[i]);
      if (kind === "code") code.push(codeText(lines[i++]));
      else if (kind === "blank" && i + 1 < lines.length && lineKind(lines[i + 1]) === "code") {
        code.push("");
        i++;
      } else break;
    }
    return [dedent(code), i];
  };
  for (let i = 0; i < lines.length; ) {
    const kind = lineKind(lines[i]);
    if (kind === "blank") {
      i++;
    } else if (kind === "heading") {
      const depth = /^#+/.exec((lines[i][0] as { text: string }).text)![0].length;
      blocks.push({ kind: "heading", depth, items: dropPrefix(lines[i], /^#+ /) });
      i++;
    } else if (kind === "code") {
      const [code, next] = takeCode(i);
      blocks.push({ kind: "code", lines: code });
      i = next;
    } else if (kind === "item") {
      const items: Array<{ items: Segment[]; code: string[] | null }> = [];
      while (i < lines.length && lineKind(lines[i]) === "item") {
        const item = { items: dropPrefix(lines[i], /^- /), code: null as string[] | null };
        i++;
        if (i < lines.length && lineKind(lines[i]) === "code") [item.code, i] = takeCode(i);
        items.push(item);
      }
      blocks.push({ kind: "list", items });
    } else {
      const para: Segment[][] = [];
      while (i < lines.length && lineKind(lines[i]) === "prose") para.push(lines[i++]);
      blocks.push({ kind: "paragraph", lines: para });
    }
  }
  return blocks;
}

// ---------------------------------------------------------------------------
// Inline Markdown
// ---------------------------------------------------------------------------

function marker(s: Extract<Segment, { kind: "conditional" }>): string {
  return `«if ${s.when === "falsy" ? "!" : ""}${s.test}»`;
}

/** A code span around `text`, fenced with more backticks than it contains. */
function codeSpan(text: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(longest + 1);
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`;
}

/** Escape what GitHub would misread in running text (never inside a code span). */
function escapeText(s: string): string {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/&(?=#?\w+;)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/~/g, "\\~")
    .replace(/\$/g, "\\$");
}

/** Escape what would start a different block at the beginning of a line. */
function escapeLineStart(s: string): string {
  return s.replace(/^(>|[+*] |\d+[.)] )/, "\\$1");
}

/**
 * Render a line's segments as inline Markdown. The prose's own code spans are
 * tracked so that escaping never reaches inside one, and a runtime value inside a
 * code span keeps its plain `${name}` spelling.
 */
function inline(items: readonly Segment[]): string {
  let out = "";
  let openFence = ""; // the backtick run that opened the current code span
  const text = (s: string) => {
    for (const part of s.split(/(`+)/)) {
      if (!part) continue;
      if (/^`+$/.test(part)) {
        if (!openFence) openFence = part;
        else if (part === openFence) openFence = "";
        out += part;
      } else out += openFence ? part : escapeText(part);
    }
  };
  for (const s of items) {
    switch (s.kind) {
      case "text":
        text(s.text);
        break;
      case "value":
        out += openFence ? `\${${s.name}}` : codeSpan(`\${${s.name}}`);
        break;
      case "conditional": {
        const lead = /^\s*/.exec(s.text)![0];
        const trail = /\s*$/.exec(s.text)![0];
        out += `${lead}${marker(s)}`;
        text(s.text.slice(lead.length, s.text.length - trail.length));
        out += `«/if»${trail}`;
        break;
      }
      case "expression":
        out += openFence ? `\${${s.source}}` : codeSpan(`\${${s.source}}`);
        break;
    }
  }
  return escapeLineStart(out);
}

function fence(lines: string[], indent: string): string {
  const longest = Math.max(0, ...lines.flatMap((l) => [...l.matchAll(/`+/g)].map((m) => m[0].length)));
  const ticks = "`".repeat(Math.max(3, longest + 1));
  return [`${ticks}js`, ...lines, ticks].map((l) => (l ? indent + l : l)).join("\n");
}

function renderBlocks(blocks: Block[]): string {
  return blocks
    .map((b) => {
      switch (b.kind) {
        case "heading":
          // One level lower: the page's own title is the only H1.
          return `${"#".repeat(Math.min(6, b.depth + 1))} ${inline(b.items)}`;
        case "paragraph":
          return b.lines.map((l) => inline(l)).join("\\\n");
        case "list":
          return b.items.map((it) => `- ${inline(it.items)}${it.code ? `\n${fence(it.code, "  ")}` : ""}`).join("\n");
        case "code":
          return fence(b.lines, "");
      }
    })
    .join("\n\n");
}

