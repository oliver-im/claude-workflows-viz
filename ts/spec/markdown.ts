/** Where a page sits, as relative links: `toSpec` reaches `spec/`, `toCapture` reaches the capture's directory. */
export interface PageLinks {
  toSpec: string;
  toCapture: string;
}

const short = (sha: string) => sha.slice(0, 12);

function bytes(n: number): string {
  return `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ",")} bytes`;
}

/** The readable page for one capture's prose. */
export function readablePage(capture: Capture, links: PageLinks, opts: { newest: boolean; hasChanges: boolean }): string {
  const sha = capture.digests[PROSE_FILE]?.sha256 ?? "";
  const firstValue = capture.segments.find((s) => s.kind === "value");
  const firstConditional = capture.segments.find((s) => s.kind === "conditional");
  const notes = [
    "- JavaScript escapes are decoded, so `\\u2014` shows as —.",
    "- The examples are code blocks, and each heading sits one level lower.",
  ];
  if (firstValue?.kind === "value") {
    notes.push(
      `- In the prose, ${codeSpan(`\${${firstValue.name}}`)} and its like mark a value the binary fills in at runtime. ` +
        "Their names are minifier output and change from release to release. " +
        `Inside the examples, ${codeSpan("${…}")} is the example's own JavaScript.`,
    );
  }
  if (firstConditional?.kind === "conditional") {
    const shown = firstConditional.when === "falsy" ? "falsy" : "truthy";
    notes.push(
      `- Text between ${codeSpan(marker(firstConditional))} and ${codeSpan("«/if»")} appears only while ` +
        `the runtime value ${codeSpan(firstConditional.test)} is ${shown}.`,
    );
  }
  const nav = [
    opts.hasChanges ? `[What changed in this release](${links.toCapture}CHANGES.md)` : null,
    `[Workflow language reference](${links.toSpec}README.md)`,
    `[Every capture](${links.toSpec}README.md#captures)`,
  ].filter(Boolean);
  const newest = opts.newest
    ? ` It is the newest capture; the same page sits beside the raw file in [\`${capture.id}/\`](${links.toCapture}).`
    : "";
  return [
    GENERATED_NOTE,
    "",
    `# Workflow tool description · cc-${capture.ccVersion}`,
    "",
    `The Workflow tool description from Claude Code ${capture.ccVersion}, captured on ${capture.capturedOn}, ` +
      `made readable.${newest} The authority is the raw capture, ` +
      `[\`${PROSE_FILE}\`](${links.toCapture}${PROSE_FILE}), whose sha256 (\`${short(sha)}…\`) the grammar gate checks. ` +
      "No word differs from it; only the display does:",
    "",
    ...notes,
    "",
    nav.join(" · "),
    "",
    "---",
    "",
    renderBlocks(parseBlocks(capture.segments)),
    "",
  ].join("\n");
}

/**
 * Prose shown literally inside an excerpt: every character Markdown could act
 * on is backslash-escaped, so the capture's own backticks and asterisks show
 * as written. Runs of spaces become no-break spaces, keeping an example's
 * indentation.
 */
function literal(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/[\\`*_[\]<>~$|{}]/g, "\\$&")
    .replace(/ {2,}/g, (run) => "&nbsp;".repeat(run.length));
}

/** A change in its mark, edge whitespace kept outside so the delimiters stay valid. */
interface Rendered {
  text: string;
  /** Escaped first / last character of the marked content, when this is a mark with no edge whitespace. */
  opens?: string;
  closes?: string;
}

function render(op: "=" | "-" | "+", text: string): Rendered {
  const [, lead, core, trail] = /^(\s*)([\s\S]*?)(\s*)$/.exec(text)!;
  if (op === "=" || !core) return { text: literal(text) };
  const mark = op === "-" ? "~~" : "**";
  const inner = literal(core);
  return {
    text: `${literal(lead)}${mark}${inner}${mark}${literal(trail)}`,
    opens: lead ? undefined : inner[0],
    closes: trail ? undefined : inner[inner.length - 1],
  };
}

const LETTER = /[\p{L}\p{N}]/u;
const PUNCT = /[\p{P}\p{S}]/u;
/** Invisible, but its source spelling ends in `;`, which lets a mark open or close against a letter. */
const ZERO_WIDTH = "&#8203;";

/**
 * Join a line's rendered runs. Markdown only opens `**`/`~~` after a space or
 * punctuation when the mark's content starts with punctuation (and closes it
 * before a letter only after a space or punctuation), so `workflows**«if !e»**`
 * would show its asterisks. A zero-width space between the letter and the mark
 * satisfies the rule without changing what the reader sees.
 */
function joinRuns(runs: Rendered[]): string {
  let out = "";
  runs.forEach((run, i) => {
    const prev = runs[i - 1];
    const before = out[out.length - 1];
    const glueOpen = run.opens !== undefined && before !== undefined && LETTER.test(before) && PUNCT.test(run.opens);
    const glueClose =
      prev?.closes !== undefined && run.text !== "" && LETTER.test(run.text[0]) && PUNCT.test(prev.closes);
    out += (glueOpen || glueClose ? ZERO_WIDTH : "") + run.text;
  });
  return out;
}

/**
 * An excerpt as a Markdown blockquote — removed text struck through (`~~`),
 * added text bold (`**`). Plain Markdown rather than `<del>`/`<ins>`, because
 * renderers that drop raw HTML (DocShelf, most sanitizers) would show nothing.
 * A mark never spans a line break: each line is marked on its own, and lines
 * join with hard breaks. A line break removed or added on its own — two lines
 * joined, or one split — shows as a marked `↵`, so the change is visible even
 * when no word changed.
 */
function excerptMarkdown(ex: Excerpt): string {
  const lines: Array<Array<{ op: "=" | "-" | "+"; text: string }>> = [[]];
  for (const p of ex.pieces) {
    const parts = p.text.split("\n");
    parts.forEach((part, i) => {
      const last = i === parts.length - 1;
      // A changed break with no changed text on its line is the whole change: draw it.
      const text = !last && p.op !== "=" && !/\S/.test(part) ? `${part}↵` : part;
      if (text) lines[lines.length - 1].push({ op: p.op, text });
      if (!last) lines.push([]);
    });
  }
  return lines
    .map((segments, i) => {
      let line = joinRuns(segments.map((s) => render(s.op, s.text)));
      // A line that would read as a list, heading, or quote marker inside the blockquote.
      line = line.replace(/^([-+#=]|\d+[.)])/, (m) => (m.length > 1 ? `${m.slice(0, -1)}\\${m.slice(-1)}` : `\\${m}`));
      if (i === 0 && ex.clippedStart) line = `… ${line}`;
      if (i === lines.length - 1 && ex.clippedEnd) line = `${line} …`;
      return `> ${line}${i < lines.length - 1 ? "\\" : ""}`;
    })
    .join("\n");
}

export interface LevelSpan {
  before: number;
  after: number;
  /** True when `after` was minted at the newer capture's release. */
  minted: boolean;
}

/** The change page for `newer` against the capture before it. */
export function changesPage(older: Capture, newer: Capture, diff: CaptureDiff, level: LevelSpan): string {
  const prev = `[cc-${older.ccVersion}](../${older.id}/workflow-tool-description.md)`;
  const levelLine = level.minted
    ? `Grammar level ${level.before} → **${level.after}**: this release minted level ${level.after}.`
    : `Grammar level ${level.after}, unchanged.`;
  const digest = (c: Capture, file: string) => {
    const d = c.digests[file];
    return d ? `${bytes(d.bytes)} · \`${short(d.sha256)}\`` : "—";
  };
  const proseSame = older.prose === newer.prose;
  const out = [
    GENERATED_NOTE,
    "",
    `# What changed in cc-${newer.ccVersion}`,
    "",
    `Claude Code ${newer.ccVersion}, captured on ${newer.capturedOn}, against the capture before it: ` +
      `${prev}, captured on ${older.capturedOn}. ${levelLine}`,
    "",
    `| Artifact | cc-${older.ccVersion} | cc-${newer.ccVersion} |`,
    "| --- | --- | --- |",
    `| [\`${PROSE_FILE}\`](${PROSE_FILE}) | ${digest(older, PROSE_FILE)} | ${proseSame ? "unchanged" : digest(newer, PROSE_FILE)} |`,
    `| [\`${SCHEMA_FILE}\`](${SCHEMA_FILE}) | ${digest(older, SCHEMA_FILE)} | ${diff.schemaChanged ? digest(newer, SCHEMA_FILE) : "unchanged"} |`,
    "",
    "## Wording",
    "",
  ];
  if (diff.excerpts.length === 0) {
    out.push(
      diff.nameProblems.length > 0
        ? "No wording changed, but runtime values moved in a way a renaming cannot explain; see below."
        : diff.renames.length > 0
          ? "No wording changed. Only the minifier's names for runtime values did, which happens on most releases."
          : "No wording changed.",
    );
    if (diff.spacingOnly.length > 0) out.push("", spacingNote(diff.spacingOnly));
  } else {
    const n = diff.excerpts.length;
    out.push(
      `${n} ${n === 1 ? "passage" : "passages"} changed: ${diff.wordsAdded} ${diff.wordsAdded === 1 ? "word" : "words"} added ` +
        `and ${diff.wordsRemoved} removed. Struck-through text was removed, and bold text was added. ` +
        "Runtime-value renames are not counted; they are listed below.",
    );
    for (const ex of diff.excerpts) {
      out.push("", `[Line ${ex.line}](${PROSE_FILE}#L${ex.line})`, "", excerptMarkdown(ex));
    }
    if (diff.spacingOnly.length > 0) out.push("", spacingNote(diff.spacingOnly));
  }
  if (diff.nameProblems.length > 0) {
    out.push("", "## Moved runtime values", "", "These name changes are not a minifier's renaming:", "");
    for (const problem of diff.nameProblems) out.push(`- ${problem}`);
  }
  if (diff.renames.length > 0) {
    out.push("", "## Renamed runtime values", "", "| Before | After |", "| --- | --- |");
    for (const [from, to] of diff.renames) out.push(`| ${codeSpan(`\${${from}}`)} | ${codeSpan(`\${${to}}`)} |`);
  }
  if (diff.schemaChanged) {
    out.push("", "## Input schema", "", "```diff");
    for (const p of diff.schemaLines) out.push(`${p.op === "=" ? " " : p.op}${p.text}`);
    out.push("```");
  }
  out.push("");
  return out.join("\n");
}

function spacingNote(lines: number[]): string {
  const links = lines.map((n) => `[${n}](${PROSE_FILE}#L${n})`).join(", ");
  return `Only spacing changed on ${lines.length === 1 ? "line" : "lines"} ${links}.`;
}

export interface CaptureRow {
  capture: Capture;
  level: number;
  minted: boolean;
  /** Null for the first capture. */
  diff: CaptureDiff | null;
}

/** The captures table, newest first, as `spec/README.md` embeds it. */
export function capturesTable(rows: CaptureRow[]): string {
  const lines = ["| Capture | Captured | Level | Change from the capture before |", "| --- | --- | --- | --- |"];
  rows.forEach((row, i) => {
    const { capture, diff } = row;
    const dir = `upstream/${capture.id}/`;
    const level = i === rows.length - 1 ? `**${row.level}** · first capture` : row.minted ? `**${row.level}** · minted` : `${row.level}`;
    let change = "—";
    if (diff) {
      const what =
        diff.excerpts.length > 0
          ? `${diff.excerpts.length} ${diff.excerpts.length === 1 ? "passage" : "passages"}, ` +
            `+${diff.wordsAdded} / −${diff.wordsRemoved} words`
          : diff.spacingOnly.length > 0
            ? "Spacing only"
            : diff.nameProblems.length > 0
              ? "Runtime values moved"
              : diff.renames.length > 0
                ? "Runtime-value renames only"
                : "None";
      change = `[${what}](${dir}CHANGES.md)${diff.schemaChanged ? "; input schema changed" : ""}`;
    }
    lines.push(`| [cc-${capture.ccVersion}](${dir}workflow-tool-description.md) | ${capture.capturedOn} | ${level} | ${change} |`);
  });
  return lines.join("\n");
}
